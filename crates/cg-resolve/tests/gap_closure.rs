#[test]
fn go_embedded_standard_library_types_take_part_in_interface_satisfaction() {
    let e = edges(&[
        GO_MOD,
        (
            "p/p.go",
            r#"package p

import (
	"io"
	"os"
	"net/http"
)

type ReadCloser interface {
	io.Reader
	Close() error
}

type OnlyClose struct{}

func (OnlyClose) Close() error { return nil }

type Both struct{}

func (Both) Read(b []byte) (int, error) { return 0, nil }
func (Both) Close() error              { return nil }

type FileBox struct{ *os.File }

type Wrapped interface {
	http.Handler
	Name() string
}

type Named struct{}

func (Named) Name() string { return "" }

type Embeds struct {
	http.Handler
	Named
}

type Fails interface {
	error
	Code() int
}

type Coded struct{}

func (Coded) Code() int { return 1 }

type CodedErr struct{}

func (CodedErr) Code() int      { return 1 }
func (CodedErr) Error() string  { return "" }
"#,
        ),
    ]);
    // io.Reader asks for Read: a type with only Close no longer satisfies the interface
    lacks(&e, "p/p.go::OnlyClose -implements-> p/p.go::ReadCloser");
    has(&e, "p/p.go::Both -implements-> p/p.go::ReadCloser");
    has(&e, "p/p.go::ReadCloser::Close -calls-> p/p.go::Both::Close");
    // *os.File brings Read and Close
    has(&e, "p/p.go::FileBox -implements-> p/p.go::ReadCloser");
    // http.Handler is opaque past its ServeHTTP: only a type embedding it as well satisfies it
    lacks(&e, "p/p.go::Named -implements-> p/p.go::Wrapped");
    has(&e, "p/p.go::Embeds -implements-> p/p.go::Wrapped");
    // the predeclared error
    lacks(&e, "p/p.go::Coded -implements-> p/p.go::Fails");
    has(&e, "p/p.go::CodedErr -implements-> p/p.go::Fails");
}

