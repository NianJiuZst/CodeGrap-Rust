#[test]
fn js_calls_through_aliases_reach_the_aliased_function() {
    let e = edges(&[
        ("package.json", r#"{"name":"demo"}"#),
        (
            "src/impl.ts",
            "export function realImpl(x: number) { return x; }\nexport function win() { return 1; }\nexport function posix() { return 2; }\nexport class Lexer { static lex() {} }\nconst isWin = false;\nexport const alias = realImpl;\nexport const pick = isWin ? win : posix;\nexport const api = { run: realImpl, posix };\nexport const lex = Lexer.lex;\nexport const keys = Object.keys;\nexport const data = { width: 5 };\n",
        ),
        (
            "src/use.ts",
            "import { alias, pick, api, data } from './impl';\nimport { realImpl } from './impl';\nexport function caller() {\n  alias(1);\n  pick();\n  api.run(2);\n  const local = realImpl;\n  local(3);\n  data.width;\n}\n",
        ),
    ]);
    // a call through a bare alias, a local alias and an object literal member
    has(&e, "src/use.ts::caller -calls-> src/impl.ts::realImpl");
    lacks(&e, "src/use.ts::caller -calls-> src/impl.ts::alias");
    // a conditional value: the call lands on the constant, which hands on both arms
    has(&e, "src/use.ts::caller -calls-> src/impl.ts::pick");
    has(&e, "src/impl.ts::pick -calls-> src/impl.ts::win");
    has(&e, "src/impl.ts::pick -calls-> src/impl.ts::posix");
    has(&e, "src/impl.ts::alias -calls-> src/impl.ts::realImpl");
    has(&e, "src/impl.ts::lex -calls-> src/impl.ts::Lexer::lex");
    // `Object.keys` is no project function; an object of data hands nothing on
    assert!(!e.iter().any(|x| x.starts_with("src/impl.ts::keys -calls->")), "{e:#?}");
    assert!(!e.iter().any(|x| x.starts_with("src/impl.ts::data -calls->")), "{e:#?}");
}

#[test]
fn es5_constructors_type_their_instances_through_prototypes() {
    let (_dir, view) = project(&[
        ("package.json", r#"{"name":"demo"}"#),
        (
            "src/proto.js",
            "var util = require('util');\nfunction Base() {}\nBase.prototype.stop = function stop() {};\nfunction Params(opts) { this.opts = opts; }\nutil.inherits(Params, Base);\nParams.prototype.render = function render() { return this.save(); };\nParams.prototype.save = function save() { return 1; };\nfunction Other() {}\nOther.prototype.render = function render() { return 2; };\nfunction use() {\n  var p = new Params({});\n  p.render();\n  p.stop();\n  new Params({}).save();\n}\nmodule.exports = use;\n",
        ),
    ]);
    let e = dump::dump_edges(&view);
    has(&e, "src/proto.js::Params -extends-> src/proto.js::Base");
    has(&e, "src/proto.js::use -calls-> src/proto.js::stop");
    has(&e, "src/proto.js::use -calls-> src/proto.js::save");
    // `p.render()` reaches Params' render (line 6), never Other's (line 9)
    let lines: Vec<u32> = view
        .files()
        .flat_map(|f| view.nodes_in_file(f))
        .map(cg_core::NodeIdx)
        .filter(|n| view.node(*n).name() == "use")
        .flat_map(|n| view.out_edges(n).filter(|ed| ed.kind == cg_core::EdgeKind::Calls).map(|ed| ed.dst).collect::<Vec<_>>())
        .filter(|d| view.node(*d).name() == "render")
        .map(|d| view.node(d).start_line())
        .collect();
    assert_eq!(lines, vec![6], "{e:#?}");
    // `this.save()` inside a prototype member is the constructor's own save
    has(&e, "src/proto.js::render -calls-> src/proto.js::save");
}

