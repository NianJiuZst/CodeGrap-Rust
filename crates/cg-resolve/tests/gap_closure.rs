//! Resolution and synthesis rules ported from upstream for the supported languages: each test
//! checks the edge the rule adds and the edges it must not invent.

use cg_resolve::{build_seg, IndexOptions};
use cg_store::{dump, View};
use std::sync::Arc;

fn project(files: &[(&str, &str)]) -> (tempfile::TempDir, View) {
    let dir = tempfile::tempdir().unwrap();
    for (path, contents) in files {
        let dest = dir.path().join(path);
        std::fs::create_dir_all(dest.parent().unwrap()).unwrap();
        std::fs::write(dest, contents).unwrap();
    }
    let seg = build_seg(dir.path(), &IndexOptions { threads: Some(2), ..Default::default() }).unwrap().seg;
    let view = View::new(Arc::new(seg)).with_root(dir.path().to_path_buf());
    (dir, view)
}

fn edges(files: &[(&str, &str)]) -> Vec<String> {
    let (_dir, view) = project(files);
    dump::dump_edges(&view)
}

#[track_caller]
fn has(edges: &[String], e: &str) {
    assert!(edges.iter().any(|x| x == e), "missing {e}\n{edges:#?}");
}

#[track_caller]
fn lacks(edges: &[String], e: &str) {
    assert!(!edges.iter().any(|x| x == e), "unexpected {e}\n{edges:#?}");
}

